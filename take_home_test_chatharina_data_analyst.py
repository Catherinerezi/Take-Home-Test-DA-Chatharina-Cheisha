def pct_safe(a, periods):
  shifted = a.shift(periods)
  return np.where(shifted != 0, (a - shifted) / shifted, np.nan)

r = raw[[LJ, CAT, VAL, DT]].copy()
r[DT] = pd.to_datetime(r[DT], errors='raise')
r['Per_M'] = r[DT].dt.to_period('M')

m = (r.groupby([LJ, CAT, 'Per_M'], as_index=False)[VAL]
  .sum().rename(columns={VAL:'Valor_Mensal'}))

def complete_months(g):
  idx = pd.period_range(g['Per_M'].min(), g['Per_M'].max(), freq='M')
  g = g.set_index('Per_M').reindex(idx, fill_value=0)
  g.index.name = 'Per_M'
  return g.reset_index()

m = (m.sort_values([LJ, CAT, 'Per_M'])
  .reset_index(drop=True))

if 'Per_M' not in m.columns:
  m['Per_M'] = pd.PeriodIndex(pd.to_datetime(m['Periode_ts']).dt.to_period('M'), freq='M')
