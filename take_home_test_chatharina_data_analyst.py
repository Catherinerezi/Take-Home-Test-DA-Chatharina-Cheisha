def to_long(df, id_cols, value_cols, section_name, rename_map=None):
  t = df.copy()
  if rename_map:
    t = t.rename(columns=rename_map)
  # hanya ambil kolom yang ada supaya aman
  cols_exist = [c for c in id_cols + value_cols if c in t.columns]
  t = t[cols_exist]
  # melt ke metric–value
  t = t.melt(id_vars=[c for c in id_cols if c in t.columns],
    value_vars=[c for c in value_cols if c in t.columns],
    var_name='metric', value_name='value')
  # buang baris yang value-nya NaN (mis. YoY awal periode)
  t = t.dropna(subset=['value'])
  t['section'] = section_name
  return t

